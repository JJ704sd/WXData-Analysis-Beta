"""Generate readable, client-bound single files from maintained daily-report code."""
import argparse
import ast
import hashlib
from pathlib import Path

from chat_release import DAILY_REPORT_VERSION


PROJECT = Path(__file__).resolve().parents[1]


def _names(node):
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
        return {node.name}
    if isinstance(node, ast.Assign):
        return {target.id for target in node.targets if isinstance(target, ast.Name)}
    return set()


def _select(path, names):
    tree = ast.parse(path.read_text(encoding='utf-8'))
    selected = [node for node in tree.body if _names(node) & set(names)]
    found = set().union(*(_names(node) for node in selected))
    if found != set(names):
        raise ValueError('Standalone source contract changed: ' + path.name)
    return selected


class _InlineImports(ast.NodeTransformer):
    def visit_ImportFrom(self, node):
        if (node.module or '').startswith(('offline_', 'chat_release')):
            return None
        return node


def standalone_source(client, project=PROJECT):
    if client not in {'wechat', 'wecom'}:
        raise ValueError('Invalid daily-report client')
    web = project / 'web_mvp'
    scripts = project / 'scripts'
    # Select shared pure functions, rather than importing the desktop, database
    # and document-reader graph into an otherwise offline report executable.
    selections = [
        (web / 'offline_chat.py', ('BEIJING', 'ArchiveError', 'DirectoryPublishError', 'publish_directory')),
        (web / 'database_snapshot.py', ('CHUNK', '_hash_file')),
        (web / 'offline_review.py', ('REVIEW_CHECKS', 'inventory')),
        (web / 'offline_images.py', ('message_nodes',)),
        (web / 'offline_reporting.py', ('REPORT_FILE',)),
        (scripts / 'chat_release.py', ('DAILY_REPORT_VERSION',)),
    ]
    nodes = ast.parse('import os\nimport time\nfrom datetime import datetime, timedelta, timezone\nfrom pathlib import Path\nimport hashlib\n').body
    source_paths = []
    for path, names in selections:
        nodes.extend(_select(path, names))
        source_paths.append(path)
    for name in ('offline_content_status.py', 'offline_daily.py', 'offline_daily_html.py'):
        path = web / name
        tree = ast.parse(path.read_text(encoding='utf-8'))
        nodes.extend(_InlineImports().visit(tree).body)
        source_paths.append(path)
    cli = scripts / 'daily_report.py'
    cli_tree = ast.parse(cli.read_text(encoding='utf-8'))
    nodes.extend(node for node in _InlineImports().visit(cli_tree).body
                 if isinstance(node, (ast.Import, ast.ImportFrom, ast.FunctionDef)))
    source_paths.append(cli)
    tree = ast.fix_missing_locations(ast.Module(body=nodes, type_ignores=[]))
    for node in ast.walk(tree):
        modules = [alias.name.split('.')[0] for alias in node.names] if isinstance(node, ast.Import) else [(node.module or '').split('.')[0]] if isinstance(node, ast.ImportFrom) else []
        if any(module not in {'argparse', 'bisect', 'collections', 'datetime', 'hashlib', 'html', 'json', 'os', 'pathlib', 're', 'shutil', 'sys', 'tempfile', 'time'} for module in modules):
            raise ValueError('A non-standard-library dependency entered the standalone report')
    provenance = '\n'.join('# ' + path.relative_to(project).as_posix() + ' sha256-utf8-lf=' + hashlib.sha256(path.read_text(encoding='utf-8').encode('utf-8')).hexdigest()
                           for path in source_paths)
    header = ('#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n'
              '# Generated by build_daily_standalone.py; edit the maintained source modules.\n'
              '# Single file, standard library only; Python 3.12+; fixed client: ' + client + '.\n'
              + provenance + '\n\n')
    source = (header + ast.unparse(tree) + '\n\nif __name__ == "__main__":\n'
              '    if sys.version_info < (3, 12):\n'
              '        raise SystemExit("Python 3.12 or later is required; Windows users may use the standalone EXE.")\n'
              '    raise SystemExit(main(' + repr(client) + ', standalone=True))\n')
    compile(source, client + '_daily_report.py', 'exec')
    return source


def write_scripts(output):
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    for client in ('wechat', 'wecom'):
        (output / (client + '_daily_report.py')).write_text(standalone_source(client), encoding='utf-8', newline='\n')
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True, help='New directory for the two generated scripts')
    parser.add_argument('--check', action='store_true', help='Check an existing generated directory without changing files')
    args = parser.parse_args(argv)
    if args.check:
        for client in ('wechat', 'wecom'):
            path = args.output / (client + '_daily_report.py')
            if not path.is_file() or path.read_text(encoding='utf-8') != standalone_source(client):
                raise SystemExit('Generated standalone scripts are stale: ' + str(path))
        print('Standalone scripts match maintained source.')
        return
    output = write_scripts(args.output)
    print('Generated ' + DAILY_REPORT_VERSION + ' standalone scripts: ' + str(output))


if __name__ == '__main__':
    main()
